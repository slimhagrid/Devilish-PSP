"""M9: the game's data goes into the EBOOT. Writes extracted/gen/rom_data.c, the 128 KB the translated code reads its graphics, maps, music and text from, as a C array.

    python tools/embed_rom.py [ROM] [--check]   (--check: only verify the ROM, write nothing)   default: the .gg in the project folder; refuses anything but Devilish (USA) (128 KB, CRC32 C01293B0)

The finished PSP program does not read the .gg any more. (tools/rdmap_report.py / NOTES "M9": the game reads about 80 KB of this image as data at run time, all of banks 3-7 and tables
in banks 0-2 that lie among the code, so the whole image is kept; zeroing the bytes of the translated instructions changes the game.) Like the rest of extracted/gen the file is derived
from the user's own ROM: local and git-ignored, never to be shared.
"""
import os
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SIZE = 131072
CRC = 0xC01293B0


def main():
    check_only = "--check" in sys.argv
    argv = [x for x in sys.argv[1:] if x != "--check"]
    path = argv[0] if argv else None
    if not path:
        gg = [f for f in os.listdir(ROOT) if f.lower().endswith(".gg")]
        if not gg:
            sys.exit("no .gg file in %s: put Devilish (USA).gg there" % ROOT)
        path = os.path.join(ROOT, gg[0])
    rom = open(path, "rb").read()
    if len(rom) != SIZE or (zlib.crc32(rom) & 0xFFFFFFFF) != CRC:
        sys.exit("%s is not Devilish (USA) (128 KB, CRC32 C01293B0): got %d bytes, CRC32 %08X" % (path, len(rom), zlib.crc32(rom) & 0xFFFFFFFF))
    if check_only:
        print("%s: Devilish (USA), CRC32 C01293B0, ok" % path)
        return
    out = os.path.join(ROOT, "extracted", "gen", "rom_data.c")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    lines = ["/* generated by tools/embed_rom.py from the user's own ROM (Devilish (USA), CRC32 C01293B0). Derived data: keep local, never share. */",
             "#include <stdint.h>",
             "const uint32_t gen_rom_size = %d;" % SIZE,
             "const uint32_t gen_rom_crc32 = 0x%08XU;" % CRC,
             "const uint8_t gen_rom_image[%d] __attribute__((aligned(16))) = {" % SIZE]
    for i in range(0, SIZE, 32):
        lines.append(",".join("0x%02x" % b for b in rom[i:i + 32]) + ",")
    lines.append("};")
    open(out, "w", newline="\n").write("\n".join(lines) + "\n")
    print("wrote %s (%d bytes of data, ROM CRC32 %08X verified)" % (out, SIZE, CRC))


if __name__ == "__main__":
    main()
